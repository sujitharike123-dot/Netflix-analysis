"""Run the Netflix analysis: SQL queries (SQLite), headline numbers and figures.

Usage (from the repo root, after src/prepare_data.py):
    python src/run_analysis.py

Writes:
    results/sql_results.md   every SQL query result as a table
    results/findings.json    the headline numbers quoted in the README
    figures/*.png            charts for the README
"""
import json
import os
import sqlite3
import sys

import pandas as pd

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
sys.path.insert(0, ROOT)
import netflix_charts as ch  # noqa: E402
from netflix_utils import PROC  # noqa: E402

FIG, RES, SQL = (os.path.join(ROOT, d) for d in ("figures", "results", "sql"))
os.makedirs(FIG, exist_ok=True)
os.makedirs(RES, exist_ok=True)

# ------------------------------------------------------------------ load into SQLite and run the SQL file
con = sqlite3.connect(":memory:")
for name in ["titles", "title_countries", "title_genres", "title_directors"]:
    pd.read_csv(os.path.join(PROC, f"{name}.csv")).to_sql(name, con, index=False)
with open(os.path.join(SQL, "netflix_queries.sql")) as f:
    blocks = [b.strip() for b in f.read().split("-- QUERY:")[1:] if b.strip()]  # [0] is the file header
Q = {}
for b in blocks:
    title, _, query = b.partition("\n")
    Q[title.strip()] = pd.read_sql_query(query, con)
with open(os.path.join(RES, "sql_results.md"), "w") as f:
    f.write("# SQL results\n\nGenerated by `src/run_analysis.py` from `sql/netflix_queries.sql`.\n\n")
    for title, res in Q.items():
        f.write(f"## {title}\n\n{res.to_markdown(index=False)}\n\n")
print(f"Ran {len(Q)} SQL queries")


def q(prefix):
    for k, v in Q.items():
        if k.startswith(prefix):
            return v
    raise KeyError(prefix)


# ------------------------------------------------------------------ headline numbers (all read from the query results)
mix = q("Catalogue mix").set_index("type")
yearly = q("Titles added per year").set_index("year")
growth = q("Catalogue growth")
countries = q("Top 10 countries")
share = q("Where new titles come from").set_index("year")
genres = q("Genre families")
ratings = q("Audience rating mix")
mature = q("Share of mature").set_index("year")
length = q("Average movie length").set_index("decade")
seasons = q("How many seasons").set_index("seasons")
fresh = q("Is the catalogue getting newer").set_index("year")
months = q("Busiest months").set_index("month")
dirs = q("Directors with the most titles")
dq = json.load(open(os.path.join(PROC, "data_quality.json")))
titles = pd.read_csv(os.path.join(PROC, "titles.csv"))

su = titles[titles["listed_in"].str.contains("Stand-Up", na=False) & (titles["type"] == "Movie")]
movies_2010s = titles[(titles["type"] == "Movie") & titles["release_year"].between(2010, 2019)]
movies_2000s = titles[(titles["type"] == "Movie") & titles["release_year"].between(2000, 2009)]
no_su = lambda d: d[~d["listed_in"].str.contains("Stand-Up", na=False)]
top5 = dirs.head(5)["director"].tolist()
td = pd.read_csv(os.path.join(PROC, "title_directors.csv"))
top5_titles = titles[titles["show_id"].isin(td[td["director"].isin(top5)]["show_id"])]

F = {
    "data": {"titles": int(len(titles)), "movies": int(mix.loc["Movie", "titles"]), "tv_shows": int(mix.loc["TV Show", "titles"]),
             "movie_share_pct": float(mix.loc["Movie", "share_pct"]), "last_date_added": dq["last_date_added"],
             "titles_added_in_partial_2020": dq["added_in_partial_year_2020"]},
    "titles_added": {int(y): int(r["titles_added"]) for y, r in yearly.iterrows()},
    "tv_share_pct_by_year": {int(y): float(r["tv_share_pct"]) for y, r in yearly.iterrows()},
    "growth_2016_to_2019_x": round(float(yearly.loc[2019, "titles_added"] / yearly.loc[2016, "titles_added"]), 1),
    "top_countries": countries[["country", "titles", "pct_of_titles_with_country"]].head(5).to_dict("records"),
    "country_share": {int(y): r.to_dict() for y, r in share.drop(columns="country_credits").iterrows()},
    "mature_pct_by_year": {int(y): float(r["mature_pct"]) for y, r in mature.iterrows()},
    "rating_mix": ratings.to_dict("records"),
    "avg_movie_minutes": {int(d): float(r["avg_minutes"]) for d, r in length.iterrows()},
    "stand_up": {"movies": int(len(su)), "avg_minutes": round(float(su["duration_min"].mean()), 1),
                 "avg_minutes_2010s_excl_stand_up": round(float(no_su(movies_2010s)["duration_min"].mean()), 1),
                 "avg_minutes_2000s_excl_stand_up": round(float(no_su(movies_2000s)["duration_min"].mean()), 1),
                 "top5_directors": top5, "top5_directors_titles": int(len(top5_titles)),
                 "top5_directors_stand_up_titles": int(top5_titles["listed_in"].str.contains("Stand-Up").sum())},
    "tv_one_season_pct": float(seasons.loc["1.0", "share_pct"]) if "1.0" in seasons.index else float(seasons.iloc[0]["share_pct"]),
    "tv_5plus_seasons": int(seasons.loc["5+", "shows"]),
    "added_within_1yr_pct": {int(y): float(r["added_within_1yr_pct"]) for y, r in fresh.iterrows()},
    "busiest_months_2016_2019": months.sort_values("titles_added", ascending=False).head(3).reset_index()[["month", "share_pct"]].to_dict("records"),
    "quietest_month_2016_2019": months.sort_values("titles_added").head(1).reset_index()[["month", "share_pct"]].to_dict("records"),
    "missing_pct": dq["missing_pct_by_column"],
}
with open(os.path.join(RES, "findings.json"), "w") as f:
    json.dump(F, f, indent=2, default=float)

# ------------------------------------------------------------------ figures
yr = yearly.reset_index()
ch.save(ch.chart_titles_added(yr[yr["year"] >= 2015]), os.path.join(FIG, "titles_added_by_year.png"))
ch.save(ch.chart_top_countries(countries), os.path.join(FIG, "top_countries.png"))
ch.save(ch.chart_country_share(share.reset_index()), os.path.join(FIG, "country_share_by_year.png"))
ch.save(ch.chart_genres(genres), os.path.join(FIG, "genres.png"))
ch.save(ch.chart_rating_mix(ratings), os.path.join(FIG, "rating_mix.png"))
ch.save(ch.chart_mature_by_year(mature.reset_index()), os.path.join(FIG, "mature_share_by_year.png"))
ch.save(ch.chart_movie_length(length.reset_index()), os.path.join(FIG, "movie_length_by_decade.png"))
ch.save(ch.chart_seasons(seasons.reset_index()), os.path.join(FIG, "tv_seasons.png"))
ch.save(ch.chart_freshness(fresh.reset_index()), os.path.join(FIG, "catalogue_freshness.png"))
ch.save(ch.chart_months(months.reset_index()), os.path.join(FIG, "months_added.png"))
print("Saved results/sql_results.md, results/findings.json and", len(os.listdir(FIG)), "figures")
print(json.dumps({k: F[k] for k in ["data", "growth_2016_to_2019_x", "stand_up", "tv_one_season_pct", "busiest_months_2016_2019", "quietest_month_2016_2019"]}, indent=2, default=float))
